  'PGPASSWORD', 'PGSERVICE', 'PGSERVICEFILE',
  'MT_TOKEN', 'MT_ORIGIN', 'MT_LOGIN_URL', 'MT_SESSION_PATH',
  'MT_BACKUP_SESSION_TOKEN_FILE', 'PORTAL_CREDENTIALS_FILE',
